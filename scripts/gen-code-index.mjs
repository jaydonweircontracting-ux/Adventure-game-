#!/usr/bin/env node
/**
 * Codebase Index Generator
 *
 * Scans src/game/ modules and builds docs/CODE_INDEX.md with:
 * - Module purpose (from file header comment)
 * - Exported symbols (functions, types, consts)
 * - Test coverage (from scripts/simulate.ts)
 *
 * Run: node scripts/gen-code-index.mjs
 * Output: docs/CODE_INDEX.md
 *
 * BUILD 537: Initial version.
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'fs';
import { join } from 'path';

const GAME_DIR = 'src/game';
const SIMULATE = 'scripts/simulate.ts';
const OUTPUT = 'docs/CODE_INDEX.md';

function getExports(content) {
  const exports = [];
  // export function name
  for (const m of content.matchAll(/^export\s+(?:async\s+)?function\s+(\w+)/gm)) {
    exports.push(`function ${m[1]}()`);
  }
  // export const/let name =
  for (const m of content.matchAll(/^export\s+(?:const|let)\s+(\w+)\s*=/gm)) {
    exports.push(`${m[1]}`);
  }
  // export type/interface name
  for (const m of content.matchAll(/^export\s+(?:type|interface)\s+(\w+)/gm)) {
    exports.push(`type ${m[1]}`);
  }
  // export class name
  for (const m of content.matchAll(/^export\s+class\s+(\w+)/gm)) {
    exports.push(`class ${m[1]}`);
  }
  return [...new Set(exports)].slice(0, 20); // cap at 20
}

function getPurpose(content, filename) {
  // First block comment or line comments at top
  const blockMatch = content.match(/^\/\*\*?\s*\n((?:\s*\*.*\n)*?)\s*\*\//);
  if (blockMatch) {
    return blockMatch[1].replace(/^\s*\*\s?/gm, '').trim().split('\n')[0].slice(0, 120);
  }
  const lineMatch = content.match(/^(?:\/\/.*\n){1,3}/);
  if (lineMatch) {
    return lineMatch[0].replace(/\/\//g, '').trim().split('\n')[0].slice(0, 120);
  }
  return '(no description)';
}

function getTestCoverage(modName) {
  if (!existsSync(SIMULATE)) return 'unknown';
  try {
    const sim = readFileSync(SIMULATE, 'utf8');
    // Count mentions of the module
    const base = modName.replace(/\.tsx?$/, '');
    const count = (sim.match(new RegExp(`from ['"].*${base}['"]`, 'g')) || []).length;
    const mentions = (sim.match(new RegExp(`\\b${base}\\b`, 'g')) || []).length;
    if (count > 0 || mentions > 5) return `tested (${mentions} refs)`;
    if (mentions > 0) return `partial (${mentions} refs)`;
    return 'not found in simulate.ts';
  } catch { return 'unknown'; }
}

const files = readdirSync(GAME_DIR)
  .filter(f => f.endsWith('.ts') || f.endsWith('.tsx'))
  .sort();

let md = `# Codebase Index\n\n`;
md += `> Auto-generated by \`scripts/gen-code-index.mjs\`. Do not edit manually.\n`;
md += `> Last generated: ${new Date().toISOString().split('T')[0]}\n\n`;
md += `## Modules (${files.length})\n\n`;
md += `| Module | Purpose | Key Exports | Test Coverage |\n`;
md += `|--------|---------|-------------|---------------|\n`;

for (const f of files) {
  const path = join(GAME_DIR, f);
  let content = '';
  try { content = readFileSync(path, 'utf8'); } catch { continue; }
  const purpose = getPurpose(content, f).replace(/\|/g, '\\|');
  const exps = getExports(content);
  const expStr = exps.slice(0, 5).join(', ').replace(/\|/g, '\\|') || '(none)';
  const cov = getTestCoverage(f);
  md += `| \`${f}\` | ${purpose} | ${expStr}${exps.length > 5 ? ` +${exps.length - 5} more` : ''} | ${cov} |\n`;
}

md += `\n## App.tsx\n\n`;
md += `Main React application (~9k lines). Contains GameField component with all gameplay state.\n`;
md += `Test hooks: \`window.__gameTest\` (testmode=1 only). See \`tests/real-game/README.md\`.\n`;

writeFileSync(OUTPUT, md);
console.log(`Wrote ${OUTPUT} (${files.length} modules)`);
