class Random {
  private value: number;

  constructor(seed: number) {
    this.value = seed || 1;
  }

  next() {
    this.value = (this.value * 1664525 + 1013904223) >>> 0;
    return this.value / 4294967296;
  }

  int(min: number, max: number) {
    return Math.floor(this.next() * (max - min + 1)) + min;
  }

  pick<T>(array: T[]) {
    return array[Math.floor(this.next() * array.length)];
  }
}

const key = (x: number, y: number) => `${x}:${y}`;

/**
 * BUILD 928: floor generation is now a layout dispatch. The selector
 * hashes (seed, floor) — see dungeonLayouts for why a stream draw was
 * wrong here — then the chosen generator builds the skeleton from the
 * caller's stream. The classic rooms layout is preserved verbatim
 * inside dungeonLayouts, and loops/caves join it. The returned kind is
 * the GENERATED kind (a degenerate loops sample falls back to rooms
 * and says so), never just the selected one.
 */
function makeMap(width: number, height: number, random: Random, floor: number, seed: number) {
  const selected = selectLayoutKind(seed, floor);
  const generated = generateLayout(selected, width, height, random, floor);
  const tiles = generated.kinds.map((row, y) =>
    row.map((kind, x) => ({ x, y, kind, seen: false, visible: false })),
  );
  return { tiles, layout: generated.kind };
}

function canStand(state: Pick<GameState, "tiles" | "monsters" | "player" | "groundItems" | "shops">, x: number, y: number) {
  const tile = state.tiles[y]?.[x];
  if (!tile || tile.kind === "wall" || tile.kind === "lava") return false;
  // BUILD 927: only LIVING monsters occupy a tile. Dead monsters used to
  // block their death tile forever (invisible corpse, "The stone
  // refuses your passage" on an empty floor) — a killed guardian could
  // permanently seal the corridor or vault behind it.
  if (state.monsters.some((monster) => monster.hp > 0 && monster.x === x && monster.y === y)) return false;
  // BUILD 930: a shopkeeper occupies its tile like a living monster.
  // It is never a monster, so nothing attacks it — but nothing may
  // stand where it stands, either. (All canStand callers pass full
  // GameState, so the shops field is always present.)
  if (state.shops?.some((shop) => shop.x === x && shop.y === y)) return false;
  if (state.player.x === x && state.player.y === y) return false;
  return true;
}

function revealAround(state: GameState) {
  for (const row of state.tiles) {
    for (const tile of row) tile.visible = false;
  }
  const radius = 6;
  for (let y = state.player.y - radius; y <= state.player.y + radius; y += 1) {
    for (let x = state.player.x - radius; x <= state.player.x + radius; x += 1) {
      const tile = state.tiles[y]?.[x];
      if (!tile) continue;
      if (Math.abs(x - state.player.x) + Math.abs(y - state.player.y) <= radius + 1) {
        tile.visible = true;
        tile.seen = true;
      }
    }
  }
}

function addLog(state: GameState, message: string) {
  state.log = [message, ...state.log].slice(0, 9);
  state.lastAction = message;
}

