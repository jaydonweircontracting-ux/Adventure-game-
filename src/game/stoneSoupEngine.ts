/** Display data for a shop good: the DUNGEON item, never catalog text. */
export function dungeonShopDisplay(itemKey: ShopItemKey): {
  name: string;
  glyph: string;
  color: string;
  description: string;
} {
  const templateKey = (DUNGEON_SHOP_ITEM as Partial<Record<ShopItemKey, "potion" | "food">>)[itemKey];
  const template = templateKey ? GROUND_ITEM_TEMPLATES[templateKey] : GROUND_ITEM_TEMPLATES.potion;
  return {
    name: template.name,
    glyph: template.glyph,
    color: template.color,
    description: template.description,
  };
}

/** Open a shop the player stands beside (Manhattan distance 1). */
export function openDungeonShop(state: GameState, shopId: string) {
  if (state.phase !== "playing") return state;
  const shop = state.shops?.find((entry) => entry.id === shopId);
  if (!shop) return state;
  if (Math.abs(shop.x - state.player.x) + Math.abs(shop.y - state.player.y) !== 1) {
    addLog(state, "You must stand beside the shopkeeper to browse.");
    return state;
  }
  state.activeShopId = shop.id;
  addLog(state, `${shop.keeperName} waves you over: "${shop.flavor}"`);
  return state;
}

/** Close the open shop (walking away also closes it, via step). */
export function closeDungeonShop(state: GameState) {
  state.activeShopId = null;
  return state;
}

/**
 * Buy one unit through the EXISTING stall ledger (buyFromStall): the
 * same not-sold / sold-out / no-gold guards, the same merchantGold
 * conservation. Atomic by construction: gold leaves and the item
 * enters the pack in the same call, or neither happens (every guard
 * returns before any mutation). The shop must be open — no remote
 * buying from across the floor. No turn advances.
 */
export function buyFromDungeonShop(state: GameState, shopId: string, itemKey: ShopItemKey) {
  if (state.phase !== "playing") return state;
  const shop = state.shops?.find((entry) => entry.id === shopId);
  if (!shop) {
    addLog(state, "The shopkeeper is gone.");
    return state;
  }
  if (state.activeShopId !== shopId) {
    addLog(state, "You must open the shop first.");
    return state;
  }
  const result = buyFromStall(shop.def, shop.stock, itemKey, state.player.gold);
  if (!result.ok) {
    addLog(
      state,
      result.reason === "sold-out"
        ? "Sold out."
        : result.reason === "no-gold"
          ? "You can't afford that."
          : "They don't sell that.",
    );
    return state;
  }
  const templateKey = (DUNGEON_SHOP_ITEM as Partial<Record<ShopItemKey, "potion" | "food">>)[itemKey];
  if (!templateKey) {
    addLog(state, "They don't sell that.");
    return state;
  }
  shop.stock = result.state;
  state.player.gold -= result.price;
  // merchantGold strictly increases per sale (prices > 0), so this id
  // is unique per sale within the shop without a module counter.
  state.player.inventory.push({
    id: `item-shop-${shop.id}-${itemKey}-${result.state.merchantGold}`,
    ...GROUND_ITEM_TEMPLATES[templateKey],
  });
  addLog(state, `You buy ${GROUND_ITEM_TEMPLATES[templateKey].name} for ${result.price} gold.`);
  return state;
}
